import { generateEvaluationDataset, getTrainTestSplit } from "./dataset.js";
import { calculateMAPE, calculateMAE, calculateRMSE, calculateCumulativeSpendError } from "./metrics.js";
import { LinearRunRateEvaluator } from "./linearEvaluator.js";
import { ARIMAEvaluator } from "./arimaEvaluator.js";

/**
 * Runs the forecasting evaluation comparison between Model A (Linear Run-Rate)
 * and Model B (ARIMA).
 *
 * Guarantees:
 * - Identical training dataset and identical held-out test period.
 * - Identical forecast horizon (e.g., 30 days).
 * - Identical MAPE calculation and zero-handling policy.
 * - Pure evaluation logic separate from production billing flow.
 *
 * @param {Object} [options]
 * @param {Array<Object>} [options.dataset] - Custom dataset (or generated by default)
 * @param {number} [options.trainDays=60] - Training window length in days
 * @param {number} [options.testDays=30] - Held-out test window length in days
 * @param {Object} [options.arimaConfig] - Custom ARIMA parameters
 * @returns {Object} Comprehensive evaluation results
 */
export function runForecastingComparison(options = {}) {
  const {
    trainDays = 60,
    testDays = 30,
    arimaConfig = { p: 1, d: 1, q: 1, verbose: false }
  } = options;

  // 1. Obtain and split dataset
  const dataset = options.dataset || generateEvaluationDataset({ days: trainDays + testDays });
  const split = getTrainTestSplit(dataset, trainDays, testDays);
  const { trainSpend, testSpend, summary } = split;
  const horizon = testDays;

  // 2. Evaluate Model A: Linear Run-Rate
  const linearModel = new LinearRunRateEvaluator().train(trainSpend);
  const linearForecast = linearModel.predict(horizon);
  const linearMape = calculateMAPE(testSpend, linearForecast);
  const linearMae = calculateMAE(testSpend, linearForecast);
  const linearRmse = calculateRMSE(testSpend, linearForecast);
  const linearCumulative = calculateCumulativeSpendError(testSpend, linearForecast);

  // 3. Evaluate Model B: ARIMA
  const arimaModel = new ARIMAEvaluator(arimaConfig).train(trainSpend);
  const arimaForecast = arimaModel.predict(horizon);
  const arimaMape = calculateMAPE(testSpend, arimaForecast);
  const arimaMae = calculateMAE(testSpend, arimaForecast);
  const arimaRmse = calculateRMSE(testSpend, arimaForecast);
  const arimaCumulative = calculateCumulativeSpendError(testSpend, arimaForecast);

  // 4. Identify winning model and delta
  const isArimaBetter = arimaMape.mape < linearMape.mape;
  const winner = isArimaBetter ? "ARIMA" : "Linear Run-Rate";
  const absoluteDeltaMape = Math.round(Math.abs(linearMape.mape - arimaMape.mape) * 100) / 100;
  const relativeMapeImprovement = linearMape.mape > 0
    ? Math.round(((linearMape.mape - arimaMape.mape) / linearMape.mape) * 10000) / 100
    : 0;

  // 5. Build daily comparison series for transparency
  const dailyComparisons = [];
  for (let i = 0; i < horizon; i++) {
    const testRecord = split.test[i];
    dailyComparisons.push({
      date: testRecord.date,
      dayIndex: i + 1,
      actual: testRecord.spend,
      linearForecast: linearForecast[i],
      arimaForecast: arimaForecast[i],
      linearAbsError: Math.round(Math.abs(testRecord.spend - linearForecast[i]) * 100) / 100,
      arimaAbsError: Math.round(Math.abs(testRecord.spend - arimaForecast[i]) * 100) / 100
    });
  }

  return {
    experimentMetadata: {
      timestamp: new Date().toISOString(),
      datasetSource: "Deterministic Synthetic SaaS Spend Series (Seed: 42)",
      totalObservations: summary.totalObservations,
      trainObservations: summary.trainObservations,
      testObservations: summary.testObservations,
      trainPeriod: `${summary.trainStartDate} to ${summary.trainEndDate}`,
      testPeriod: `${summary.testStartDate} to ${summary.testEndDate}`,
      forecastHorizonDays: horizon
    },
    models: {
      linearRunRate: {
        name: "Linear Run-Rate",
        modelType: "linear_run_rate",
        mape: linearMape.mape,
        formattedMape: linearMape.formattedMape,
        mae: linearMae,
        rmse: linearRmse,
        cumulativeSpend: linearCumulative,
        metadata: linearModel.getMetadata()
      },
      arima: {
        name: "ARIMA",
        modelType: "arima",
        mape: arimaMape.mape,
        formattedMape: arimaMape.formattedMape,
        mae: arimaMae,
        rmse: arimaRmse,
        cumulativeSpend: arimaCumulative,
        metadata: arimaModel.getMetadata()
      }
    },
    summaryTable: [
      {
        Model: "Linear Run-Rate",
        MAPE: linearMape.formattedMape,
        MAE: `$${linearMae.toFixed(2)}`,
        RMSE: `$${linearRmse.toFixed(2)}`,
        "Cumulative Forecast": `$${linearCumulative.totalForecast.toFixed(2)}`,
        "Actual Spend": `$${linearCumulative.totalActual.toFixed(2)}`
      },
      {
        Model: "ARIMA",
        MAPE: arimaMape.formattedMape,
        MAE: `$${arimaMae.toFixed(2)}`,
        RMSE: `$${arimaRmse.toFixed(2)}`,
        "Cumulative Forecast": `$${arimaCumulative.totalForecast.toFixed(2)}`,
        "Actual Spend": `$${arimaCumulative.totalActual.toFixed(2)}`
      }
    ],
    outcome: {
      winner,
      lowerMapeModel: winner,
      linearMape: linearMape.mape,
      arimaMape: arimaMape.mape,
      absoluteDeltaMape,
      relativeMapeImprovementPercentage: relativeMapeImprovement,
      recommendation: isArimaBetter
        ? "ARIMA demonstrated lower MAPE on non-linear seasonal data. However, due to external dependencies, higher compute overhead, and minimum series requirements, MeterFlow should retain the zero-dependency Linear Run-Rate for lightweight real-time operational budgeting while offering ARIMA for batch/offline planning."
        : "Linear Run-Rate performed better or comparably, validating retention of the current production model."
    },
    dailyComparisons
  };
}
